const DOMAIN_ORDER = ["love", "wealth", "career", "growth", "destiny", "choice"];

function countMatches(text, terms, weight) {
  return terms.reduce((score, term) => score + (text.includes(term.toLowerCase()) ? weight : 0), 0);
}

export function classifyQuestion(rawQuestion) {
  const question = String(rawQuestion || "").trim().toLowerCase();
  const scores = {};

  for (const [id, book] of Object.entries(BOOKS)) {
    const strongWeight = id === "choice" ? 2.3 : 4.2;
    const normalWeight = id === "choice" ? 1.4 : 2.1;
    scores[id] = countMatches(question, book.keywords.strong, strongWeight)
      + countMatches(question, book.keywords.normal, normalWeight);
  }

  // Questions without an explicit domain, but shaped as a dilemma, belong to Choice.
  if (/吗[？?]?$/.test(question) || /\?$/.test(question)) scores.choice += 0.35;
  if (/(还是|或者|抑或)/.test(question) || /\b(or|either)\b/.test(question)) scores.choice += 1.8;
  if (/(未来|以后|最终|会不会)/.test(question) || /\b(future|eventually|will i)\b/.test(question)) scores.destiny += 0.7;

  let selected = "destiny";
  let highest = 0;

  for (const id of DOMAIN_ORDER) {
    if (scores[id] > highest) {
      selected = id;
      highest = scores[id];
    }
  }

  if (highest === 0 && (/(应该|要不要|是否|该不该|选择|决定)/.test(question) || /\b(should|choose|decide)\b/.test(question))) {
    selected = "choice";
  }

  return { book: BOOKS[selected], scores };
}

function hashString(text) {
  let hash = 2166136261;
  for (let i = 0; i < text.length; i += 1) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

export function chooseAnswer(book, question, entropy = Date.now()) {
  const seed = hashString(`${book.id}:${question}:${Math.floor(entropy / 1000)}`);
  const index = seed % book.answers.length;
  return { zh: book.answers[index], en: book.answersEn[index] };
}

export function formatSavedTime(isoDate, locale = "zh-CN") {
  const date = new Date(isoDate);
  if (Number.isNaN(date.getTime())) return locale.startsWith("en") ? "Unknown time" : "未知时间";
  return new Intl.DateTimeFormat(locale, {
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    hour12: false
  }).format(date);
}
